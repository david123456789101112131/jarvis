"""Bilingual domain knowledge used by the offline generators.

A *domain* is a kind of business or topic (coffee shop, fashion store, SaaS, clinic…). Every
generator that needs realistic copy, colors, icons or demo data asks `detect_domain(brief)` and
reads the result, so a brief like "אתר לבית קפה" yields warm browns, a coffee icon, coffee
products and coffee-flavoured slogans everywhere.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ._util import keyword_in, norm


@dataclass(frozen=True)
class Feature:
    icon: str
    title: dict[str, str]
    text: dict[str, str]


@dataclass(frozen=True)
class Product:
    key: str
    name: dict[str, str]
    category: dict[str, str]
    price: dict[str, float]  # "he" -> ILS, "en" -> USD
    description: dict[str, str]
    icon: str


@dataclass(frozen=True)
class Domain:
    key: str
    keywords: tuple[str, ...]
    mood: str | None
    hue: float | None  # OKLCH hue in degrees
    icons: tuple[str, ...]
    label: dict[str, str]  # what the business is ("בית קפה" / "coffee shop")
    offer: dict[str, str]  # the core offering
    essence: dict[str, str]  # short noun phrase ("קפה טוב" / "great coffee")
    audience: dict[str, tuple[str, ...]]
    features: tuple[Feature, ...]
    roots: tuple[str, ...]  # English brand-name roots
    names_he: tuple[str, ...]  # curated Hebrew brand-name ideas
    kpis: dict[str, tuple[str, ...]]
    emoji: str = "✨"
    products: tuple[Product, ...] = field(default=())

    def t(self, attr: str, lang: str) -> str:
        value = getattr(self, attr)
        return value.get(lang) or value["en"]


def _f(icon: str, he_title: str, he_text: str, en_title: str, en_text: str) -> Feature:
    return Feature(icon, {"he": he_title, "en": en_title}, {"he": he_text, "en": en_text})


def _p(key: str, he: str, en: str, cat_he: str, cat_en: str, ils: float, usd: float, desc_he: str, desc_en: str,
       icon: str) -> Product:
    return Product(key, {"he": he, "en": en}, {"he": cat_he, "en": cat_en}, {"he": ils, "en": usd},
                   {"he": desc_he, "en": desc_en}, icon)


def _kpi(he: tuple[str, ...], en: tuple[str, ...]) -> dict[str, tuple[str, ...]]:
    return {"he": he, "en": en}


