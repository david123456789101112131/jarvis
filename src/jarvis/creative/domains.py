# Words that name the medium rather than the business ("a fitness app", "אפליקציה לחדר כושר"):
# they count for less, so the subject of the brief wins over the platform it will run on.
WEAK_KEYWORDS = frozenset({"app", "apps", "אפליקציה", "אפליקציית", "platform", "dashboard", "דשבורד", "data",
                           "software", "תוכנה", "game", "games", "משחק", "משחקים", "store", "shop"})


def domain_scores(text: str) -> list[tuple[Domain, float]]:
    """Every domain with at least one keyword hit, best first (ties keep declaration order)."""
    hay = norm(text or "")
    scored: list[tuple[Domain, float]] = []
    for d in DOMAINS:
        score = 0.0
        for kw in d.keywords:
            if keyword_in(hay, kw, normalized=True):
                score += 0.4 if kw in WEAK_KEYWORDS else 1.0
        if score > 0:
            scored.append((d, score))
    return sorted(scored, key=lambda ds: -ds[1])


def detect_domain(text: str) -> Domain:
    """The domain a brief is about, or `GENERIC` when nothing matches."""
    scores = domain_scores(text or "")
    return scores[0][0] if scores else GENERIC
